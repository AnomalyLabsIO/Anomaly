using System.Text;
using Mono.Cecil;

if (args.Length is < 2 or > 3)
{
    Console.Error.WriteLine("Usage: PublicApiBaseline <assembly.dll> <baseline.txt> [--update]");
    return 2;
}

var assemblyPath = Path.GetFullPath(args[0]);
var baselinePath = Path.GetFullPath(args[1]);
var update = args.Length == 3 && string.Equals(args[2], "--update", StringComparison.Ordinal);
if (args.Length == 3 && !update)
{
    Console.Error.WriteLine("The only supported third argument is --update.");
    return 2;
}
if (!File.Exists(assemblyPath))
{
    Console.Error.WriteLine("Assembly not found: " + assemblyPath);
    return 2;
}

var current = Generate(assemblyPath);
if (update)
{
    Directory.CreateDirectory(Path.GetDirectoryName(baselinePath)!);
    File.WriteAllText(baselinePath, current, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
    Console.WriteLine("Updated public API baseline: " + baselinePath);
    return 0;
}
if (!File.Exists(baselinePath))
{
    Console.Error.WriteLine("Public API baseline not found: " + baselinePath);
    return 1;
}

var expected = Normalize(File.ReadAllText(baselinePath));
if (string.Equals(expected, current, StringComparison.Ordinal))
{
    Console.WriteLine("Public API baseline matches.");
    return 0;
}

var expectedLines = expected.Split('\n').ToHashSet(StringComparer.Ordinal);
var currentLines = current.Split('\n').ToHashSet(StringComparer.Ordinal);
Console.Error.WriteLine("Public API baseline changed. Review compatibility, then update intentionally.");
foreach (var removed in expectedLines.Except(currentLines).OrderBy(line => line, StringComparer.Ordinal).Take(50))
    Console.Error.WriteLine("- " + removed);
foreach (var added in currentLines.Except(expectedLines).OrderBy(line => line, StringComparer.Ordinal).Take(50))
    Console.Error.WriteLine("+ " + added);
return 1;

static string Generate(string path)
{
    using var assembly = AssemblyDefinition.ReadAssembly(path, new ReaderParameters
    {
        ReadSymbols = false,
        ReadingMode = ReadingMode.Immediate,
    });
    var lines = new SortedSet<string>(StringComparer.Ordinal)
    {
        "# Anomaly.Client.Api public surface v1",
        "# Generated by tools/PublicApiBaseline; update only after compatibility review.",
    };

    foreach (var type in assembly.MainModule.Types.SelectMany(Flatten).Where(IsPubliclyVisible))
    {
        var interfaces = string.Join(",", type.Interfaces.Select(item => item.InterfaceType.FullName)
            .OrderBy(name => name, StringComparer.Ordinal));
        lines.Add($"T|{type.FullName}|{TypeKind(type)}|base={type.BaseType?.FullName ?? ""}|ifaces={interfaces}|gp={GenericParameters(type.GenericParameters)}");

        foreach (var field in type.Fields.Where(IsVisible))
            lines.Add($"F|{field.FullName}|static={field.IsStatic}|readonly={field.IsInitOnly}|const={field.HasConstant}");
        foreach (var method in type.Methods.Where(IsVisible))
            lines.Add($"M|{method.FullName}|static={method.IsStatic}|virtual={method.IsVirtual}|abstract={method.IsAbstract}|gp={GenericParameters(method.GenericParameters)}");
        foreach (var property in type.Properties.Where(property =>
                     IsVisible(property.GetMethod) || IsVisible(property.SetMethod)))
            lines.Add($"P|{property.FullName}|get={Visibility(property.GetMethod)}|set={Visibility(property.SetMethod)}");
        foreach (var eventDefinition in type.Events.Where(eventDefinition =>
                     IsVisible(eventDefinition.AddMethod) || IsVisible(eventDefinition.RemoveMethod)))
            lines.Add($"E|{eventDefinition.FullName}|add={Visibility(eventDefinition.AddMethod)}|remove={Visibility(eventDefinition.RemoveMethod)}");
    }

    return Normalize(string.Join('\n', lines) + "\n");
}

static IEnumerable<TypeDefinition> Flatten(TypeDefinition type)
{
    yield return type;
    foreach (var nested in type.NestedTypes.SelectMany(Flatten)) yield return nested;
}

static bool IsPubliclyVisible(TypeDefinition type) =>
    type.IsPublic || (type.IsNestedPublic && type.DeclaringType != null && IsPubliclyVisible(type.DeclaringType));

static bool IsVisible(IMemberDefinition? member) => member switch
{
    MethodDefinition method => method.IsPublic || method.IsFamily || method.IsFamilyOrAssembly,
    FieldDefinition field => field.IsPublic || field.IsFamily || field.IsFamilyOrAssembly,
    _ => false,
};

static string Visibility(MethodDefinition? method)
{
    if (method == null) return "none";
    if (method.IsPublic) return "public";
    if (method.IsFamilyOrAssembly) return "protected-internal";
    if (method.IsFamily) return "protected";
    return "nonpublic";
}

static string TypeKind(TypeDefinition type)
{
    if (type.IsInterface) return "interface";
    if (type.IsEnum) return "enum";
    if (type.IsValueType) return "struct";
    if (type.BaseType?.FullName == "System.MulticastDelegate") return "delegate";
    return "class";
}

static string GenericParameters(IEnumerable<GenericParameter> parameters) => string.Join(";",
    parameters.Select(parameter => parameter.Name + ":" + parameter.Attributes + ":" +
        string.Join(",", parameter.Constraints.Select(constraint => constraint.ConstraintType.FullName)
            .OrderBy(name => name, StringComparer.Ordinal))));

static string Normalize(string value) => value.Replace("\r\n", "\n", StringComparison.Ordinal)
    .Replace('\r', '\n');
