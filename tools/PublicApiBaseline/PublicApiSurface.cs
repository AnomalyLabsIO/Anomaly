using System.Globalization;
using System.Text.Json;
using Mono.Cecil;

internal static class PublicApiSurface
{
    internal static string Generate(string path)
    {
        using var assembly = AssemblyDefinition.ReadAssembly(path, new ReaderParameters
        {
            ReadSymbols = false,
            ReadingMode = ReadingMode.Immediate,
        });
        return Generate(assembly);
    }

    internal static string Generate(AssemblyDefinition assembly)
    {
        var lines = new SortedSet<string>(StringComparer.Ordinal)
        {
            $"# {assembly.Name.Name} public surface v2",
            "# Generated by tools/PublicApiBaseline; update only after compatibility review.",
        };
        foreach (var type in assembly.MainModule.Types.SelectMany(Flatten).Where(IsPubliclyVisible))
        {
            var interfaces = string.Join(",", type.Interfaces.Select(item => item.InterfaceType.FullName)
                .OrderBy(name => name, StringComparer.Ordinal));
            lines.Add($"T|{type.FullName}|{TypeKind(type)}|base={type.BaseType?.FullName ?? ""}|ifaces={interfaces}|gp={GenericParameters(type.GenericParameters)}|access={TypeVisibility(type)}|abstract={type.IsAbstract}|sealed={type.IsSealed}");
            foreach (var field in type.Fields.Where(IsVisible))
                lines.Add($"F|{field.FullName}|static={field.IsStatic}|readonly={field.IsInitOnly}|const={field.HasConstant}|value={Constant(field.HasConstant, field.Constant)}|access={FieldVisibility(field)}{ConstantAttributes(field.CustomAttributes, "|")}");
            foreach (var method in type.Methods.Where(IsVisible))
                lines.Add($"M|{method.FullName}|static={method.IsStatic}|virtual={method.IsVirtual}|abstract={method.IsAbstract}|gp={GenericParameters(method.GenericParameters)}|access={Visibility(method)}|final={method.IsFinal}|newslot={method.IsNewSlot}|params={Parameters(method.Parameters)}");
            foreach (var property in type.Properties.Where(property => IsVisible(property.GetMethod) || IsVisible(property.SetMethod)))
                lines.Add($"P|{property.FullName}|get={Visibility(property.GetMethod)}|set={Visibility(property.SetMethod)}|params={Parameters(property.Parameters)}");
            foreach (var evt in type.Events.Where(evt => IsVisible(evt.AddMethod) || IsVisible(evt.RemoveMethod)))
                lines.Add($"E|{evt.FullName}|add={Visibility(evt.AddMethod)}|remove={Visibility(evt.RemoveMethod)}");
        }
        return string.Join('\n', lines) + "\n";
    }

    private static string Parameters(IEnumerable<ParameterDefinition> parameters) => string.Join(";", parameters.Select(p =>
        $"{Escape(p.Name)}:in={p.IsIn}:out={p.IsOut}:optional={p.IsOptional}:default={Constant(p.HasConstant, p.Constant)}:params={p.CustomAttributes.Any(a => a.AttributeType.FullName == "System.ParamArrayAttribute")}{ConstantAttributes(p.CustomAttributes, ":")}"));

    // Decimal constants/defaults and DateTime defaults live in attributes rather
    // than the metadata Constant table. Keep ordinary members' records unchanged.
    private static string ConstantAttributes(IEnumerable<CustomAttribute> attributes, string separator)
    {
        var values = attributes.Where(attribute => attribute.AttributeType.FullName is
                "System.Runtime.CompilerServices.DecimalConstantAttribute" or
                "System.Runtime.CompilerServices.DateTimeConstantAttribute")
            .Select(attribute => Escape(attribute.Constructor.FullName) + "(" +
                string.Join(",", attribute.ConstructorArguments.Select(argument =>
                    Escape(argument.Type.FullName) + "=" + Constant(true, argument.Value))) + ")")
            .OrderBy(value => value, StringComparer.Ordinal).ToArray();
        return values.Length == 0 ? string.Empty : separator + "constant-attributes=" + string.Join(",", values);
    }

    private static string Constant(bool present, object? value)
    {
        if (!present) return "none";
        if (value == null) return "null";
        return value switch
        {
            string text => "string:" + Escape(text),
            char character => "char:" + ((int)character).ToString(CultureInfo.InvariantCulture),
            float number => "Single:" + number.ToString("R", CultureInfo.InvariantCulture),
            double number => "Double:" + number.ToString("R", CultureInfo.InvariantCulture),
            IFormattable number => value.GetType().Name + ":" + number.ToString(null, CultureInfo.InvariantCulture),
            _ => value.GetType().Name + ":" + Escape(value.ToString() ?? ""),
        };
    }

    // JSON escaping also escapes delimiters so one public default cannot inject records.
    private static string Escape(string text) => JsonSerializer.Serialize(text)
        .Replace("|", "\\u007C", StringComparison.Ordinal)
        .Replace(";", "\\u003B", StringComparison.Ordinal)
        .Replace(":", "\\u003A", StringComparison.Ordinal);

    private static IEnumerable<TypeDefinition> Flatten(TypeDefinition type)
    {
        yield return type;
        foreach (var nested in type.NestedTypes.SelectMany(Flatten)) yield return nested;
    }

    private static bool IsPubliclyVisible(TypeDefinition type) => type.IsPublic ||
        ((type.IsNestedPublic || type.IsNestedFamily || type.IsNestedFamilyOrAssembly) &&
         type.DeclaringType != null && IsPubliclyVisible(type.DeclaringType));

    private static bool IsVisible(IMemberDefinition? member) => member switch
    {
        MethodDefinition method => method.IsPublic || method.IsFamily || method.IsFamilyOrAssembly,
        FieldDefinition field => field.IsPublic || field.IsFamily || field.IsFamilyOrAssembly,
        _ => false,
    };

    private static string Visibility(MethodDefinition? method) => method == null ? "none" :
        method.IsPublic ? "public" : method.IsFamilyOrAssembly ? "protected-internal" : method.IsFamily ? "protected" : "nonpublic";
    private static string FieldVisibility(FieldDefinition field) => field.IsPublic ? "public" :
        field.IsFamilyOrAssembly ? "protected-internal" : "protected";
    private static string TypeVisibility(TypeDefinition type) => type.IsPublic || type.IsNestedPublic ? "public" :
        type.IsNestedFamilyOrAssembly ? "protected-internal" : "protected";

    private static string TypeKind(TypeDefinition type) => type.IsInterface ? "interface" : type.IsEnum ? "enum" :
        type.IsValueType ? "struct" : type.BaseType?.FullName == "System.MulticastDelegate" ? "delegate" : "class";

    private static string GenericParameters(IEnumerable<GenericParameter> parameters) => string.Join(";",
        parameters.Select(parameter => parameter.Name + ":" + parameter.Attributes + ":" +
            string.Join(",", parameter.Constraints.Select(constraint => constraint.ConstraintType.FullName)
                .OrderBy(name => name, StringComparer.Ordinal))));
}
